import fs from 'fs-extra';
import path from 'path';
import type { PluginOption } from "vite";

/**
 * Cria um plugin Vite para gerar um arquivo index.d.ts que importa todas as definições de tipo.
 * @returns {import('vite').Plugin}
 */
export function indexPlugin(desiredOutDirs?: string[]): PluginOption {
	let compiledOutputPath: string;
	let outDirs: string[];


  return {
    name: 'vite-plugin-index',

    /**
     * Obtém as configurações de output do Rollup para determinar o diretório de saída.
     * @param {import('vite').ResolvedConfig} config
     */
    configResolved(config) {
      compiledOutputPath = config.build.outDir || 'dist';
			outDirs = desiredOutDirs || [compiledOutputPath];
    },

    /**
     * Hook executado após o Rollup ter concluído a criação do bundle.
     */
    async closeBundle() {
			const filePaths = fs
				.globSync(`${compiledOutputPath}/**/*.d.ts`);
			outDirs.forEach(async (outDir) => {
				try {
					if (filePaths.length === 0) {
						console.log('[index] Nenhum arquivo .d.ts encontrado para importar.');
						return;
					}

					let index: string = `// Generated by IndexPlugin.\n\n`;
					let indexDTS: string = `// Generated by IndexPlugin.\n\n`;
					let indexCJS: string = `// Generated by IndexPlugin.\n\n`;

					filePaths.forEach(filePath => {
						let relativePath = path.relative(outDir, filePath);
						relativePath = relativePath.replace(/\.d\.ts$/, '');
						relativePath = relativePath.replace(/\\/g, '/');
						index += `export * from './${relativePath}.js';\n`;
						indexCJS += `exports.${path.basename(relativePath)} = require('./${relativePath}.cjs');\n`;
						indexDTS += `export * from './${relativePath}';\n`;
					});

					await fs.outputFile(path.join(outDir, 'index.d.ts'), indexDTS);
					await fs.outputFile(path.join(outDir, 'index.js'), index);
					await fs.outputFile(path.join(outDir, 'index.cjs'), indexCJS);
				} catch (error) {
					console.error('[index] Erro ao criar o index.d.ts:', error);
				}
			});
    },
  };
}


export function createIndexFile(srcDir: string) {
	const filePaths = fs
		.globSync(`${srcDir}/**/*.{tsx,ts,js}`)
		.filter(filePath => !filePath.endsWith('.d.ts') && !filePath.endsWith('index.ts'));

	if (filePaths.length === 0) {
		console.log('[index] Nenhum arquivo .ts encontrado para importar.');
		return;
	}

	let index: string = `// Generated by createIndexFile.\n\n`;

	filePaths.forEach(filePath => {
		let relativePath = path.relative(srcDir, filePath);
		relativePath = relativePath.replace(/\.[^/.]+$/, '');
		relativePath = relativePath.replace(/\\/g, '/');
		index += `export * from './${relativePath}';\n`;
	});

	fs.outputFileSync(path.join(srcDir, 'index.ts'), index);
}
